"""Write reconciliation results into the seed (additions) + emit corrections.

Additions are durable via the deploy-run ``sync-admin-hierarchy.mjs`` (upsert
only). Same-tier conflicts (a ward already mapped to a different constituency)
require a human-approved correction migration — additions never generate one.

Everything here is pure/functional over in-memory lists; the CLI owns the actual
file reads/writes and the ``--apply`` gate.
"""

from __future__ import annotations

import json
from datetime import date
from pathlib import Path

from .paths import SEED_DIR

CONSTITUENCY_WARDS_SEED = SEED_DIR / "constituency-wards.json"
SENATORIAL_LGAS_SEED = SEED_DIR / "senatorial-district-lgas.json"


def _today_month() -> str:
    return date.today().strftime("%Y-%m")


def apply_additions(
    existing_rows: list[dict],
    new_maps: list[tuple[str, str, str]],
    source: str,
    source_url: str,
    source_date: str | None = None,
) -> list[dict]:
    """Merge ``(constituency_code, ward_code, confidence)`` additions into the
    constituency-wards seed shape.

    Keyed by ``(constituency_code, ward_code)``: existing pairs are left fully
    untouched (no source/confidence overwrite); unrelated rows pass through
    unchanged; only genuinely new pairs are appended.
    """
    source_date = source_date or _today_month()
    seen: set[tuple[str, str]] = {
        (r["constituency_code"], r["ward_code"]) for r in existing_rows
    }
    merged = list(existing_rows)
    for constituency_code, ward_code, confidence in new_maps:
        key = (constituency_code, ward_code)
        if key in seen:
            continue
        seen.add(key)
        merged.append(
            {
                "constituency_code": constituency_code,
                "ward_code": ward_code,
                "source": source,
                "source_url": source_url,
                "source_date": source_date,
                "confidence": confidence,
            }
        )
    return merged


