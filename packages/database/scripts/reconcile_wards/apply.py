def emit_corrections_migration(conflicts: list[dict]) -> str | None:
    """Build a migration SQL string that removes the stale same-tier mapping for
    each human-approved conflict. The seed then carries the corrected mapping,
    which the deploy-run sync upserts.

    Returns None when there are no conflicts (additions need no migration).
    """
    if not conflicts:
        return None
    lines = [
        "-- Ward-reconciliation corrections: remove stale same-tier ward mappings",
        "-- so the corrected seed mapping (loaded by sync-admin-hierarchy.mjs) wins.",
        "-- Generated by reconcile_wards.apply.emit_corrections_migration.",
        "",
    ]
    for c in conflicts:
        ward = c["ward_code"].replace("'", "''")
        existing = c["existing_constituency"].replace("'", "''")
        proposed = c.get("proposed_constituency", "")
        lines.append(
            f"-- ward {ward}: {existing} -> {proposed} (tier {c.get('tier', '?')})"
        )
        lines.append(
            "DELETE FROM constituency_wards "
            f"WHERE ward_code = '{ward}' "
            f"AND constituency_code = '{existing}';"
        )
    lines.append("")
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# File IO helpers (used by the CLI's --apply path)
# ---------------------------------------------------------------------------


def load_seed(path: Path) -> list[dict]:
    return json.loads(path.read_text())


def write_seed(path: Path, rows: list[dict]) -> None:
    path.write_text(json.dumps(rows, indent=2) + "\n")
